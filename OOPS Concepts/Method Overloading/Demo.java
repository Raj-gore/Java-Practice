
// Method Overloading-
// in java method overloading is a concept where , one class contain 2 or more method comtain with same name but differnt parameter


class Demo
{
	void m1()
	{
		System.out.println("No arg m1 methos called");
	}
	void m1(int a)
	{
		System.out.println("int arg m1 methos called");
	}
	void m1(int a , int b)
	{
		System.out.println("int int arg m1 methos called");
	}
}