public class IfElseIfExample {
    public static void main(String args[])
    {
        int marks = 81;

        if(marks > 90)
        {
            System.out.print("Grade A");
        } 
        else if(marks > 70)
        {
            System.out.print("Grade B");
        }
        else if(marks > 50)
        {
            System.out.print("GRade C");
        }  
        else
        {
            System.out.print("Fail");
        }                          
    }
}
